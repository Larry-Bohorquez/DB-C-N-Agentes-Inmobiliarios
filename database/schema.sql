-- 1. TABLAS

CREATE TABLE DOCUMENT_TYPE (
    ID CHARACTER VARYING NOT NULL PRIMARY KEY,
    NAME CHARACTER VARYING
);

CREATE TABLE NEIGHBORHOOD (
    ID CHARACTER VARYING NOT NULL PRIMARY KEY,
    NAME CHARACTER VARYING
);

CREATE TABLE SALES_CONSULTANT (
    ID CHARACTER VARYING NOT NULL PRIMARY KEY,
    FIRST_NAME CHARACTER VARYING,
    MIDDLE_NAME CHARACTER VARYING,
    FIRST_SURNAME CHARACTER VARYING,
    SECOND_SURNAME CHARACTER VARYING,
    PHONE CHARACTER VARYING,
    EMAIL CHARACTER VARYING
);

CREATE TABLE CUSTOMER (
    ID CHARACTER VARYING NOT NULL,
    DOCUMENT_TYPE_ID CHARACTER VARYING NOT NULL,
    DOCUMENT_NUMBER CHARACTER VARYING,
    FIRST_NAME CHARACTER VARYING,
    MIDDLE_NAME CHARACTER VARYING,
    FIRST_SURNAME CHARACTER VARYING,
    SECOND_SURNAME CHARACTER VARYING,
    PHONE CHARACTER VARYING,
    EMAIL CHARACTER VARYING,
    BUDGET DECIMAL,
    PRIMARY KEY (ID, DOCUMENT_TYPE_ID),
    FOREIGN KEY (DOCUMENT_TYPE_ID) REFERENCES DOCUMENT_TYPE(ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE PROPERTY (
    ID CHARACTER VARYING NOT NULL,
    NEIGHBORHOOD_ID CHARACTER VARYING NOT NULL,
    ADDRESS CHARACTER VARYING,
    OPERATION_TYPE CHARACTER VARYING,
    AREA DECIMAL,
    ROOMS INTEGER,
    BATHROOMS INTEGER,
    STATUS CHARACTER VARYING,
    SALE_PRICE DECIMAL,
    RENTAL_RATE DECIMAL,
    PRIMARY KEY (ID, NEIGHBORHOOD_ID),
    FOREIGN KEY (NEIGHBORHOOD_ID) REFERENCES NEIGHBORHOOD(ID)
        ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE CONTRACT_RENTAL (
    CUSTOMER_ID CHARACTER VARYING NOT NULL,
    CUSTOMER_DOCUMENT_TYPE_ID CHARACTER VARYING NOT NULL,
    PROPERTY_ID CHARACTER VARYING NOT NULL,
    PROPERTY_NEIGHBORHOOD_ID CHARACTER VARYING NOT NULL,
    SALES_CONSULTANT_ID CHARACTER VARYING,
    START_DATE DATE,
    DURATION INTEGER,
    RENTAL_VALUE DECIMAL,
    DEPOSIT_VALUE DECIMAL,
    PRIMARY KEY (
        CUSTOMER_ID,
        CUSTOMER_DOCUMENT_TYPE_ID,
        PROPERTY_ID,
        PROPERTY_NEIGHBORHOOD_ID
    ),
    FOREIGN KEY (CUSTOMER_ID, CUSTOMER_DOCUMENT_TYPE_ID)
        REFERENCES CUSTOMER(ID, DOCUMENT_TYPE_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (PROPERTY_ID, PROPERTY_NEIGHBORHOOD_ID)
        REFERENCES PROPERTY(ID, NEIGHBORHOOD_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (SALES_CONSULTANT_ID) REFERENCES SALES_CONSULTANT(ID)
        ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE CONTRACT_SALE (
    PROPERTY_ID CHARACTER VARYING NOT NULL,
    PROPERTY_NEIGHBORHOOD_ID CHARACTER VARYING NOT NULL,
    CUSTOMER_ID CHARACTER VARYING NOT NULL,
    CUSTOMER_DOCUMENT_TYPE_ID CHARACTER VARYING NOT NULL,
    SALES_CONSULTANT_ID CHARACTER VARYING,
    SALE_DATE DATE,
    AGREED_VALUE DECIMAL,
    DEED_DATE DATE,
    PRIMARY KEY (
        PROPERTY_ID,
        PROPERTY_NEIGHBORHOOD_ID,
        CUSTOMER_ID,
        CUSTOMER_DOCUMENT_TYPE_ID
    ),
    FOREIGN KEY (PROPERTY_ID, PROPERTY_NEIGHBORHOOD_ID)
        REFERENCES PROPERTY(ID, NEIGHBORHOOD_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (CUSTOMER_ID, CUSTOMER_DOCUMENT_TYPE_ID)
        REFERENCES CUSTOMER(ID, DOCUMENT_TYPE_ID)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (SALES_CONSULTANT_ID) REFERENCES SALES_CONSULTANT(ID)
        ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE CLAUSE (
    ID CHARACTER VARYING NOT NULL PRIMARY KEY,
    DESCRIPTION CHARACTER VARYING,

    CONTRACT_RENTAL_CUSTOMER_ID CHARACTER VARYING,
    CONTRACT_RENTAL_DOCUMENT_TYPE_ID CHARACTER VARYING,
    CONTRACT_RENTAL_PROPERTY_ID CHARACTER VARYING,
    CONTRACT_RENTAL_PROPERTY_NEIGHBORHOOD_ID CHARACTER VARYING,

    CONTRACT_SALE_PROPERTY_ID CHARACTER VARYING,
    CONTRACT_SALE_NEIGHBORHOOD_ID CHARACTER VARYING,
    CONTRACT_SALE_CUSTOMER_ID CHARACTER VARYING,
    CONTRACT_SALE_DOCUMENT_TYPE_ID CHARACTER VARYING,

    FOREIGN KEY (
        CONTRACT_RENTAL_CUSTOMER_ID,
        CONTRACT_RENTAL_DOCUMENT_TYPE_ID,
        CONTRACT_RENTAL_PROPERTY_ID,
        CONTRACT_RENTAL_PROPERTY_NEIGHBORHOOD_ID
    )
    REFERENCES CONTRACT_RENTAL (
        CUSTOMER_ID,
        CUSTOMER_DOCUMENT_TYPE_ID,
        PROPERTY_ID,
        PROPERTY_NEIGHBORHOOD_ID
    )
    ON DELETE CASCADE ON UPDATE CASCADE,

    FOREIGN KEY (
        CONTRACT_SALE_PROPERTY_ID,
        CONTRACT_SALE_NEIGHBORHOOD_ID,
        CONTRACT_SALE_CUSTOMER_ID,
        CONTRACT_SALE_DOCUMENT_TYPE_ID
    )
    REFERENCES CONTRACT_SALE (
        PROPERTY_ID,
        PROPERTY_NEIGHBORHOOD_ID,
        CUSTOMER_ID,
        CUSTOMER_DOCUMENT_TYPE_ID
    )
    ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE AUDIT_LOG (
    ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TABLE_NAME VARCHAR,
    OPERATION VARCHAR,
    DETAIL VARCHAR,
    EVENT_DATE TIMESTAMP DEFAULT NOW()
);
